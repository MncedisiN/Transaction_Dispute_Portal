-- One settings table retains the family definition and every immutable publication.
-- Publication identifiers, JSON bodies, audit attribution and effective dates are preserved.
CREATE TEMP TABLE settings_permissions ON COMMIT DROP AS
SELECT DISTINCT principal.rolname, access.privilege_type
FROM pg_class settings
JOIN pg_namespace domain ON domain.oid = settings.relnamespace
CROSS JOIN LATERAL aclexplode(COALESCE(settings.relacl, acldefault('r', settings.relowner))) access
JOIN pg_roles principal ON principal.oid = access.grantee
WHERE domain.nspname = 'configuration'
    AND settings.relname IN ('settings', 'settingVersions')
    AND access.grantee <> 0
    AND access.privilege_type IN ('SELECT', 'INSERT', 'UPDATE');

CREATE TEMP TABLE settings_family_map ON COMMIT DROP AS
SELECT
    id AS "previousId",
    (SELECT COALESCE(MAX(id), 0) FROM configuration."settingVersions")
        + ROW_NUMBER() OVER (ORDER BY id) AS "currentId"
FROM configuration."settings";

CREATE TABLE configuration."settingsConsolidation" (
    "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "policyId" bigint NOT NULL,
    "supersedesVersionId" bigint,
    "publicId" uuid NOT NULL UNIQUE,
    "version" int NOT NULL,
    "priority" int NOT NULL DEFAULT 0,
    "effectiveFromUtc" timestamptz NOT NULL,
    "effectiveToUtc" timestamptz,
    "publishedAtUtc" timestamptz,
    "createdAtUtc" timestamptz,
    "createdByPublicId" uuid,
    "sourceUpdatedAtUtc" timestamptz,
    "recordedAtUtc" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "changeReason" varchar(500) NOT NULL,
    "isDeleted" boolean NOT NULL DEFAULT false,
    "deletedAtUtc" timestamptz,
    "deletedByPublicId" uuid,
    "deletionReason" varchar(500),
    "requestId" uuid,
    "requestFingerprint" varchar(64),
    "sourceVersionPublicId" uuid,
    "provenance" varchar(32) NOT NULL,
    "body" jsonb NOT NULL,
    "configurationKey" bigint,
    "code" varchar(64),
    "lastVersion" int,
    "concurrencyToken" bigint,
    UNIQUE ("policyId", "version"),
    CHECK ("effectiveToUtc" IS NULL OR "effectiveToUtc" > "effectiveFromUtc"),
    CHECK ("version" = 0 OR (body ->> 'version')::int = "version"),
    CHECK (("version" = 0 AND "policyId" = "id" AND "code" IS NOT NULL AND "publishedAtUtc" IS NULL
        AND "configurationKey" IS NOT NULL AND "lastVersion" > 0 AND "concurrencyToken" > 0)
        OR ("version" > 0 AND "code" IS NULL AND "configurationKey" IS NULL
        AND "lastVersion" IS NULL AND "concurrencyToken" IS NULL AND "publishedAtUtc" IS NOT NULL)),
    CHECK (("isDeleted" AND "deletedAtUtc" IS NOT NULL AND "deletedByPublicId" IS NOT NULL AND "deletionReason" IS NOT NULL)
        OR (NOT "isDeleted" AND "deletedAtUtc" IS NULL AND "deletedByPublicId" IS NULL AND "deletionReason" IS NULL))
);

