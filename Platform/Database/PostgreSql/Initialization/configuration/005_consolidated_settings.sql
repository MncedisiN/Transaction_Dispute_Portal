CREATE OR REPLACE FUNCTION configuration.protect_setting_version() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Settings definitions and publications are retained';
    END IF;
    IF OLD.version = 0 THEN
        IF (to_jsonb(NEW) - ARRAY['lastVersion', 'concurrencyToken']) IS DISTINCT FROM
            (to_jsonb(OLD) - ARRAY['lastVersion', 'concurrencyToken'])
            OR NEW."lastVersion" < OLD."lastVersion" OR NEW."concurrencyToken" <= OLD."concurrencyToken" THEN
            RAISE EXCEPTION 'Settings identity and revision counters cannot be reset';
        END IF;
    ELSIF OLD."isDeleted" OR NOT NEW."isDeleted" OR
        (to_jsonb(NEW) - ARRAY['isDeleted', 'deletedAtUtc', 'deletedByPublicId', 'deletionReason']) IS DISTINCT FROM
        (to_jsonb(OLD) - ARRAY['isDeleted', 'deletedAtUtc', 'deletedByPublicId', 'deletionReason']) THEN
        RAISE EXCEPTION 'Published settings and removal attribution are immutable';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER protect_setting_version BEFORE UPDATE OR DELETE ON configuration."settings"
    FOR EACH ROW EXECUTE FUNCTION configuration.protect_setting_version();
DROP FUNCTION configuration.protect_settings_counter();

DO $$
DECLARE
    permission record;
BEGIN
    FOR permission IN SELECT rolname, privilege_type FROM settings_permissions LOOP
        EXECUTE format('GRANT %s ON TABLE configuration."settings" TO %I', permission.privilege_type, permission.rolname);
        IF permission.privilege_type = 'INSERT' THEN
            EXECUTE format('GRANT USAGE ON SEQUENCE configuration.settings_id_seq TO %I', permission.rolname);
        END IF;
    END LOOP;
END $$;
