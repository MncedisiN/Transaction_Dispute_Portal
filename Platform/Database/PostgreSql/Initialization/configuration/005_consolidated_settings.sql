INSERT INTO configuration."settingsConsolidation" (
    "id", "policyId", "publicId", "version", "effectiveFromUtc", "changeReason",
    "provenance", "body", "configurationKey", "code", "lastVersion", "concurrencyToken"
)
SELECT
    m."currentId", m."currentId", p."publicId", 0, CURRENT_TIMESTAMP,
    'Settings family retained during consolidation.', 'InitialDefinition', first.body,
    p.id, p.code, p."lastVersion", p."concurrencyToken"
FROM configuration."settings" p
JOIN settings_family_map m ON m."previousId" = p.id
JOIN LATERAL (
    SELECT body
    FROM configuration."settingVersions"
    WHERE "policyId" = p.id
    ORDER BY version
    LIMIT 1
) first ON TRUE;

DO $$
BEGIN
    IF (SELECT COUNT(*) FROM configuration."settingsConsolidation" WHERE version > 0)
        <> (SELECT COUNT(*) FROM configuration."settingVersions")
        OR (SELECT COUNT(*) FROM configuration."settingsConsolidation" WHERE version = 0)
        <> (SELECT COUNT(*) FROM configuration."settings")
        OR EXISTS (
            SELECT to_jsonb(v) - 'policyId'
            FROM configuration."settingVersions" v
            EXCEPT
            SELECT to_jsonb(v) - ARRAY['policyId', 'configurationKey', 'code', 'lastVersion', 'concurrencyToken']
            FROM configuration."settingsConsolidation" v
            WHERE version > 0
        ) THEN
        RAISE EXCEPTION 'Settings consolidation did not preserve the original publications';
    END IF;
END $$;

